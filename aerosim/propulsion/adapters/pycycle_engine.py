"""pyCycle backend (NASA, built on OpenMDAO; NPSS-style element-based cycles).

Plan:
1. ``build()`` assembles a pyc.Cycle (FlightConditions -> Inlet -> Compressor ->
   Combustor -> Turbine -> Nozzle, Shaft, Performance). Start from pyCycle's
   ``example_cycles/simple_turbojet.py`` and ``high_bypass_turbofan.py``.
2. One design point (sizes the engine), then off-design points for the deck.
3. Optional: replace default compressor/turbine maps with maps generated by
   ``adapters/turbomachinery.py`` (TurboFlow meanline) for the actual blade geometry.

Because pyCycle is an OpenMDAO model, this class also exposes ``as_subsystem()``
so optimization/ can couple engine sizing directly with a Dymos trajectory.
"""

from __future__ import annotations

from aerosim.core import EngineDeck, registry, require


@registry.register("airbreathing", "pycycle")
class PyCycleEngine:
    def __init__(self, architecture: str = "turbojet", design: dict | None = None,
                 maps: dict | None = None) -> None:
        self.architecture = architecture
        self.design = design or {}
        self.maps = maps or {}
        self._prob = None

    def build(self):
        require("pycycle.api", "airbreathing")
        require("openmdao.api", "optim")
        raise NotImplementedError(
            f"TODO: assemble pyCycle '{self.architecture}' model (see module docstring)"
        )

    def as_subsystem(self):
        """Return the pyCycle group for embedding in a larger OpenMDAO problem."""
        return self.build()

    def operating_point(self, altitude: float, mach: float, power: float) -> dict[str, float]:
        raise NotImplementedError

    def deck(self, altitudes, machs, powers) -> EngineDeck:
        raise NotImplementedError
