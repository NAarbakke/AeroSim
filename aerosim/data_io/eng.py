"""RASP .eng thrust-curve files (the format used by OpenRocket, thrustcurve.org, openMotor export).

Header: name diameter_mm length_mm delays propellant_kg total_kg manufacturer
Body:   time_s thrust_N  (pairs, last thrust 0)
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from aerosim.core import ThrustCurve


def read_eng(path: str | Path) -> ThrustCurve:
    lines = [ln.split(";")[0].strip() for ln in Path(path).read_text().splitlines()]
    lines = [ln for ln in lines if ln]
    name, _dia, _len, _delays, prop_kg, total_kg, *_ = lines[0].split()
    pts = np.array([[float(x) for x in ln.split()[:2]] for ln in lines[1:]])
    t, F = pts[:, 0], pts[:, 1]
    if t[0] > 0:
        t, F = np.insert(t, 0, 0.0), np.insert(F, 0, 0.0)
    prop = float(prop_kg)
    # mass flow assumed proportional to thrust (constant Isp), the RASP convention
    mdot = F * prop / np.trapezoid(F, t)
    return ThrustCurve(t, F, mdot, prop, float(total_kg) - prop, name)


def write_eng(curve: ThrustCurve, path: str | Path, diameter_mm: float = 54.0,
              length_mm: float = 300.0, delays: str = "0", manufacturer: str = "aerosim") -> Path:
    path = Path(path)
    total = curve.propellant_mass + curve.dry_mass
    lines = ["; generated by aerosim",
             (f"{curve.name.replace(' ', '_')} {diameter_mm:g} {length_mm:g} {delays} "
             f"{curve.propellant_mass:.4f} {total:.4f} {manufacturer}")]
    lines += [f"{t:.4f} {f:.3f}" for t, f in zip(curve.time, curve.thrust) if t > 0]
    path.write_text("\n".join(lines) + "\n")
    return path
